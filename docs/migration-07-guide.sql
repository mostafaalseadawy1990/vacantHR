create table if not exists public.guide_sections (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  title text not null,
  body_md text not null default '',
  video_url text,
  position int not null default 0,
  published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.guide_sections enable row level security;

drop policy if exists "guide public read" on public.guide_sections;
drop policy if exists "guide admin write" on public.guide_sections;
create policy "guide public read" on public.guide_sections
  for select using (published or public.is_admin());
create policy "guide admin write" on public.guide_sections
  for all using (public.is_admin()) with check (public.is_admin());

